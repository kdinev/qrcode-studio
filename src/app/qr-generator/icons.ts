let registered = false;

/** Registers the app icon collection once, no matter how many views ask for it. */
export function registerAppIcons(): void {
  if (registered) {
    return;
  }

  registered = true;

  for (const [name, path] of Object.entries(ICON_PATHS)) {
    registerIconFromText(
      name,
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path d="${path}"/></svg>`,
      APP_ICONS
    );
  }
}
